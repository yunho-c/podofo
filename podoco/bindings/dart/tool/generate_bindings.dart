import 'dart:io';

import 'package:ffigen/ffigen.dart';

Future<void> main(List<String> args) async {
  if (args.isNotEmpty && (args.length != 1 || args.single != '--check')) {
    throw ArgumentError(
      'Usage: dart run tool/generate_bindings.dart [--check]',
    );
  }
  final check = args.isNotEmpty;
  final packageRoot = Platform.script.resolve('../');
  final committed = File.fromUri(
    packageRoot.resolve('lib/src/bindings.g.dart'),
  );
  final generated = check
      ? File.fromUri(
          packageRoot.resolve('.dart_tool/podoco-check/bindings.g.dart'),
        )
      : committed;
  await generated.parent.create(recursive: true);
  final libclangPath = Platform.environment['LIBCLANG_PATH'];
  await FfiGenerator(
    output: Output(
      dart: DartOutput(path: generated.uri),
      style: const NativeExternalBindings(
        assetId: 'package:podoco/src/bindings.g.dart',
      ),
      preamble: '// Generated by ffigen. Do not edit by hand.',
    ),
    input: Input(
      entryPoints: [packageRoot.resolve('../../include/podoco.h')],
      include: (header) => header.pathSegments.last == 'podoco.h',
    ),
    visitors: [
      Visitor(
        func: (node) => node.isIncluded = node.name.startsWith('podoco_'),
        struct: (node) => node.isIncluded = node.name.startsWith('Podoco'),
        macroConstant: (node) =>
            node.isIncluded = node.name.startsWith('PODOCO_'),
      ),
    ],
  ).generate(
    libclangDylib: libclangPath == null ? null : File(libclangPath).uri,
  );
  if (check &&
      await generated.readAsString() != await committed.readAsString()) {
    stderr.writeln(
      'Dart bindings are stale; run python3 tools/dev.py generate.',
    );
    exitCode = 1;
  }
  final fixture = File.fromUri(
    packageRoot.resolve('../../tests/fixtures/domain/updates.json'),
  );
  final mirror = File.fromUri(
    packageRoot.resolve('test/fixtures/updates.json'),
  );
  if (check) {
    if (!await mirror.exists() ||
        await fixture.readAsString() != await mirror.readAsString()) {
      throw StateError('Dart schema fixture is stale; regenerate bindings.');
    }
  } else {
    await mirror.parent.create(recursive: true);
    await fixture.copy(mirror.path);
  }
}
